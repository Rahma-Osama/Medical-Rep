class MedicalEntity {
  final String name;
  final String specialty;
  final String category;
  final String hospital;
  final String phone;
  final String email;
  final String address;

  const MedicalEntity({
    required this.name,
    required this.specialty,
    required this.category,
    required this.hospital,
    required this.phone,
    required this.email,
    required this.address,
  });
}